-- COMMAND ----------

MERGE INTO stagedoor_gold.dim_customer AS d
USING (SELECT -1 AS customer_sk) AS s ON d.customer_sk = s.customer_sk
WHEN NOT MATCHED THEN INSERT (customer_sk, customer_id, full_name, city, valid_from, valid_to, is_current)
  VALUES (-1, 'UNKNOWN', 'Unknown customer', 'Unknown', TIMESTAMP'1900-01-01', TIMESTAMP'9999-12-31', true);

MERGE INTO stagedoor_gold.dim_event AS d
USING (SELECT -1 AS event_sk) AS s ON d.event_sk = s.event_sk
WHEN NOT MATCHED THEN INSERT (event_sk, event_id, event_name) VALUES (-1, 'UNKNOWN', 'Unknown event');

MERGE INTO stagedoor_gold.dim_date AS d
USING (
  SELECT CAST(date_format(dt, 'yyyyMMdd') AS INT) AS date_key, dt AS full_date, date_format(dt, 'EEEE') AS day_name,
         date_format(dt, 'yyyy-MM') AS month, concat(year(dt), '-Q', quarter(dt)) AS quarter, dayofweek(dt) IN (1, 7) AS is_weekend
  FROM (SELECT explode(sequence(DATE'2025-01-01', DATE'2027-12-31', INTERVAL 1 DAY)) AS dt)
) AS s ON d.date_key = s.date_key
WHEN NOT MATCHED THEN INSERT *;

