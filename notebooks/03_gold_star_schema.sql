CREATE TABLE IF NOT EXISTS stagedoor_gold.dim_customer (
  customer_sk   BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) COMMENT 'Surrogate key: one per customer version',
  customer_id   STRING    NOT NULL COMMENT 'Business key from the ticketing system',
  full_name     STRING             COMMENT 'Type 1: latest value on every version',
  email         STRING             COMMENT 'Type 1: latest value on every version',
  city          STRING             COMMENT 'Type 2: a change creates a new version',
  country       STRING             COMMENT 'Type 2',
  loyalty_tier  STRING             COMMENT 'Type 2',
  valid_from    TIMESTAMP NOT NULL COMMENT 'Inclusive. The first version starts at 1900-01-01 so early facts still match',
  valid_to      TIMESTAMP NOT NULL COMMENT 'Exclusive. 9999-12-31 for the current version',
  is_current    BOOLEAN   NOT NULL,
  CONSTRAINT dim_customer_pk PRIMARY KEY (customer_sk) RELY
) CLUSTER BY (customer_id) COMMENT 'Customer dimension, SCD Type 2';

CREATE TABLE IF NOT EXISTS stagedoor_gold.dim_event (
  event_sk    BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  event_id    STRING NOT NULL, event_name STRING, artist STRING, venue STRING, city STRING,
  event_date  DATE, base_price DECIMAL(10,2) COMMENT 'Current list price. What customers paid is on the fact',
  CONSTRAINT dim_event_pk PRIMARY KEY (event_sk) RELY
) CLUSTER BY (event_id) COMMENT 'Event dimension, SCD Type 1';

CREATE TABLE IF NOT EXISTS stagedoor_gold.dim_date (
  date_key INT NOT NULL COMMENT 'yyyyMMdd', full_date DATE NOT NULL, day_name STRING, month STRING, quarter STRING, is_weekend BOOLEAN,
  CONSTRAINT dim_date_pk PRIMARY KEY (date_key) RELY
) COMMENT 'Calendar dimension';

CREATE TABLE IF NOT EXISTS stagedoor_gold.fact_ticket_sales (
  order_id      STRING NOT NULL COMMENT 'Degenerate dimension: the order number itself',
  date_key      INT    NOT NULL,
  customer_sk   BIGINT NOT NULL COMMENT 'The customer version valid when the order was placed',
  event_sk      BIGINT NOT NULL,
  quantity      INT,
  unit_price    DECIMAL(10,2) COMMENT 'Price actually paid, not the current list price',
  gross_amount  DECIMAL(12,2),
  order_status  STRING,
  CONSTRAINT fact_ticket_sales_pk PRIMARY KEY (order_id) RELY,
  CONSTRAINT fact_ticket_sales_date_fk FOREIGN KEY (date_key) REFERENCES stagedoor_gold.dim_date,
  CONSTRAINT fact_ticket_sales_customer_fk FOREIGN KEY (customer_sk) REFERENCES stagedoor_gold.dim_customer,
  CONSTRAINT fact_ticket_sales_event_fk FOREIGN KEY (event_sk) REFERENCES stagedoor_gold.dim_event
) CLUSTER BY (date_key, event_sk) COMMENT 'Ticket sales at order grain';

