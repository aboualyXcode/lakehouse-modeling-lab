-- MAGIC %md
-- MAGIC ## Ask it something
-- MAGIC Paid revenue by the customer's city **at the time of purchase**. After batch 2, Amara's first order still
-- MAGIC counts in Berlin even though she now lives in Lisbon.

-- COMMAND ----------

SELECT c.city, SUM(f.gross_amount) AS revenue
FROM stagedoor_gold.fact_ticket_sales f
JOIN stagedoor_gold.dim_customer c ON c.customer_sk = f.customer_sk
WHERE f.order_status = 'PAID'
GROUP BY c.city
ORDER BY revenue DESC;
