-- MAGIC ## dim_event: SCD Type 1

-- COMMAND ----------

MERGE INTO stagedoor_gold.dim_event AS d
USING stagedoor_silver.events AS s
ON d.event_id = s.event_id
WHEN MATCHED AND struct(d.event_name, d.artist, d.venue, d.city, d.event_date, d.base_price)
             IS DISTINCT FROM struct(s.event_name, s.artist, s.venue, s.city, s.event_date, s.base_price) THEN
  UPDATE SET d.event_name = s.event_name, d.artist = s.artist, d.venue = s.venue,
             d.city = s.city, d.event_date = s.event_date, d.base_price = s.base_price
WHEN NOT MATCHED THEN
  INSERT (event_id, event_name, artist, venue, city, event_date, base_price)
  VALUES (s.event_id, s.event_name, s.artist, s.venue, s.city, s.event_date, s.base_price);

