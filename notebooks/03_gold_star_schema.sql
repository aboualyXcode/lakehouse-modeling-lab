-- MAGIC %md
-- MAGIC # 03 · Gold: the star schema
-- MAGIC
-- MAGIC ```
-- MAGIC                 dim_date
-- MAGIC                    │
-- MAGIC   dim_customer ── fact_ticket_sales ── dim_event
-- MAGIC   (SCD Type 2)     grain: one order      (SCD Type 1)
-- MAGIC ```
-- MAGIC
-- MAGIC **Design decisions**
-- MAGIC - **Grain:** one row per order (a transaction fact that carries the order's current status).
-- MAGIC - **Surrogate keys** are identity columns: assigned once, never reused, never changed.
-- MAGIC - **History:** `dim_customer` is SCD Type 2 on `city`, `country` and `loyalty_tier` (they change reporting);
-- MAGIC   `full_name` and `email` are Type 1 (overwritten on every version).
-- MAGIC - **Unknown members** (`-1`) keep facts loadable when a dimension row has not arrived yet.
-- MAGIC - **Constraints** are informational in Databricks: `PRIMARY KEY ... RELY` lets the optimizer trust them,
-- MAGIC   and BI tools read them to build joins. They are not enforced, so `06_validate` checks them.
-- MAGIC - **Liquid clustering** (`CLUSTER BY`) instead of partitioning, on the columns people filter and join by.

