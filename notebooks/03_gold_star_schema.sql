-- MAGIC %md
-- MAGIC ## fact_ticket_sales
-- MAGIC The customer key is looked up **as of the order time**. Orders whose customer has not arrived point to `-1`;
-- MAGIC because the whole fact is re-derived from Silver, they are re-pointed automatically once the customer arrives.

-- COMMAND ----------

MERGE INTO stagedoor_gold.fact_ticket_sales AS f
USING (
  SELECT o.order_id,
         CAST(date_format(o.order_ts, 'yyyyMMdd') AS INT) AS date_key,
         COALESCE(c.customer_sk, -1)                      AS customer_sk,
         COALESCE(e.event_sk, -1)                         AS event_sk,
         o.quantity, o.unit_price,
         CAST(o.quantity * o.unit_price AS DECIMAL(12,2)) AS gross_amount,
         o.status                                         AS order_status
  FROM stagedoor_silver.orders o
  LEFT JOIN stagedoor_gold.dim_customer c
    ON c.customer_id = o.customer_id AND o.order_ts >= c.valid_from AND o.order_ts < c.valid_to
  LEFT JOIN stagedoor_gold.dim_event e ON e.event_id = o.event_id
) AS s
ON f.order_id = s.order_id
WHEN MATCHED AND struct(f.customer_sk, f.event_sk, f.quantity, f.unit_price, f.order_status)
             IS DISTINCT FROM struct(s.customer_sk, s.event_sk, s.quantity, s.unit_price, s.order_status) THEN UPDATE SET *
WHEN NOT MATCHED THEN INSERT *;

