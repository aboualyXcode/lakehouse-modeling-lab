-- MAGIC %md
-- MAGIC ## dim_customer: SCD Type 2 that survives late data
-- MAGIC
-- MAGIC The classic SCD2 MERGE compares the incoming row with the *current* version, which only works if
-- MAGIC changes arrive in order. Here, versions are derived from Silver's full change history in business time,
-- MAGIC then merged on `(customer_id, valid_from)`:
-- MAGIC - a late change becomes a new version in the middle of the history, and its neighbours' dates adjust;
-- MAGIC - existing versions keep their surrogate keys;
-- MAGIC - a version that late data makes redundant is removed, and `fact_ticket_sales` is re-pointed below.
-- MAGIC
-- MAGIC A declarative pipeline gets the same behaviour from `AUTO CDC ... STORED AS SCD TYPE 2`
-- MAGIC (see `pipelines/medallion_pipeline.sql`).

-- COMMAND ----------

CREATE OR REPLACE TEMPORARY VIEW customer_versions AS
WITH ordered AS (
  SELECT *, LAG(struct(city, country, loyalty_tier)) OVER (PARTITION BY customer_id ORDER BY updated_at, _ingested_at) AS prev_tracked
  FROM stagedoor_silver.customer_changes
), starts AS (
  SELECT customer_id, city, country, loyalty_tier, updated_at,
         ROW_NUMBER() OVER (PARTITION BY customer_id ORDER BY updated_at, _ingested_at) AS version_no
  FROM ordered
  WHERE prev_tracked IS NULL OR prev_tracked IS DISTINCT FROM struct(city, country, loyalty_tier)
)
SELECT s.customer_id, c.full_name, c.email, s.city, s.country, s.loyalty_tier,
       IF(s.version_no = 1, TIMESTAMP'1900-01-01', s.updated_at)            AS valid_from,
       COALESCE(LEAD(s.updated_at) OVER w, TIMESTAMP'9999-12-31')            AS valid_to,
       LEAD(s.updated_at) OVER w IS NULL                                      AS is_current
FROM starts s
JOIN stagedoor_silver.customers c USING (customer_id)
WINDOW w AS (PARTITION BY s.customer_id ORDER BY s.updated_at);

-- COMMAND ----------

MERGE INTO stagedoor_gold.dim_customer AS d
USING customer_versions AS v
ON d.customer_id = v.customer_id AND d.valid_from = v.valid_from
WHEN MATCHED AND (d.valid_to <> v.valid_to OR d.is_current <> v.is_current
                  OR d.full_name IS DISTINCT FROM v.full_name OR d.email IS DISTINCT FROM v.email
                  OR struct(d.city, d.country, d.loyalty_tier) IS DISTINCT FROM struct(v.city, v.country, v.loyalty_tier)) THEN
  UPDATE SET d.valid_to = v.valid_to, d.is_current = v.is_current, d.full_name = v.full_name, d.email = v.email,
             d.city = v.city, d.country = v.country, d.loyalty_tier = v.loyalty_tier
WHEN NOT MATCHED THEN
  INSERT (customer_id, full_name, email, city, country, loyalty_tier, valid_from, valid_to, is_current)
  VALUES (v.customer_id, v.full_name, v.email, v.city, v.country, v.loyalty_tier, v.valid_from, v.valid_to, v.is_current)
WHEN NOT MATCHED BY SOURCE AND d.customer_sk <> -1 THEN DELETE;

